// protoc-gen-go-muxkit 从 protobuf service 方法上的 google.api.http 注解生成样板代码。
//
// 用法：
//
//	protoc --go_out=. --go-grpc_out=. --go-muxkit_out=. \
//	    --go-muxkit_opt=muxkit_import=github.com/your/muxkit \
//	    api.proto
//
// 生成三类东西：
//  1. RegisterXxxRoutes：把 grpc service 实现挂到 muxkit 路由上
//  2. bindXxxRequest：完整的参数绑定函数（path / query / body），零反射
//  3. 路由的文档元数据（operationId / tags / summary）
//
// 注意本插件**不生成**参数校验和 OpenAPI 文档：
// 校验交给 buf protovalidate（约束写在 proto 里），文档交给 gnostic。
//
// 绑定才是没有现成方案的部分——标准库 ServeMux 的 path 参数只能通过
// r.PathValue(key) 逐个取，不像 query / header 是 url.Values 能被通用库整体处理。
// 既然 path 和 body 的映射已由 google.api.http 在生成期确定，
// 那就把整个绑定逻辑生成出来，运行时一次反射都不用做。
package main

import (
	"fmt"
	"regexp"
	"sort"
	"strings"

	"google.golang.org/genproto/googleapis/api/annotations"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
)

// muxkitImport 是核心库的 Go import path，可用 muxkit_import 参数覆盖。
var muxkitImport = "muxkit"

var pathParamRe = regexp.MustCompile(`\{([^}/]+)\}`)

func main() {
	var flags flagSet
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		flags.parse(gen.Request.GetParameter())
		for _, f := range gen.Files {
			if !f.Generate || len(f.Services) == 0 {
				continue
			}
			generate(gen, f)
		}
		return nil
	})
}

// flagSet 解析 --go-muxkit_opt 传进来的参数。
type flagSet struct{}

func (flagSet) parse(param string) {
	for _, kv := range strings.Split(param, ",") {
		k, v, ok := strings.Cut(strings.TrimSpace(kv), "=")
		if !ok {
			continue
		}
		if k == "muxkit_import" {
			muxkitImport = v
		}
	}
}

// imports 记录生成代码实际用到的包，避免产出未使用的 import。
type imports struct{ set map[string]bool }

func (im *imports) add(p string) { im.set[p] = true }

func (im *imports) list() []string {
	out := make([]string, 0, len(im.set))
	for p := range im.set {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

type methodCode struct {
	reg  string // 路由注册语句
	bind string // 绑定函数
}

func generate(gen *protogen.Plugin, f *protogen.File) {
	g := gen.NewGeneratedFile(f.GeneratedFilenamePrefix+".muxkit.go", f.GoImportPath)

	im := &imports{set: map[string]bool{}}
	var services []string
	var binds []string

	for _, svc := range f.Services {
		var stmts []string
		for _, m := range svc.Methods {
			code := buildMethod(g, m, svc, im)
			if code == nil {
				continue
			}
			stmts = append(stmts, code.reg)
			binds = append(binds, code.bind)
		}
		if len(stmts) == 0 {
			continue
		}
		var b strings.Builder
		fmt.Fprintf(&b, "// Register%sRoutes 把 %s 的实现挂到 HTTP 路由上。\n", svc.GoName, svc.GoName)
		fmt.Fprintf(&b, "func Register%sRoutes(r *muxkit.Router, srv %sServer) {\n", svc.GoName, svc.GoName)
		for _, s := range stmts {
			_, _ = b.WriteString("\t" + s + "\n")
		}
		b.WriteString("}\n")
		services = append(services, b.String())
	}

	if len(services) == 0 {
		g.Skip()
		return
	}

	g.P("// Code generated by protoc-gen-go-muxkit. DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	g.P("package ", f.GoPackageName)
	g.P()
	// 只要有绑定函数，就一定要 protojson 渲染器：响应不能用 encoding/json
	if len(binds) > 0 {
		im.add("google.golang.org/protobuf/proto")
		im.add("reflect")
		binds = append(binds, protoRendererSource())
	}

	g.P("import (")
	paths := append(im.list(), muxkitImport)
	sort.Strings(paths)
	for _, p := range paths {
		if p == muxkitImport {
			g.P("\tmuxkit ", quoted(p))
			continue
		}
		g.P("\t", quoted(p))
	}
	g.P(")")
	g.P()
	for _, s := range services {
		g.P(s)
	}
	for _, b := range binds {
		g.P(b)
	}
}

// protoRendererSource 生成统一的响应渲染函数。
//
// 不能用 encoding/json：在 protobuf 的 JSON 约定里 int64 是字符串、enum 是名字，
// 而生成的结构体上没有对应的 encoding/json 语义，直接渲染会输出数字，
// 和 grpc-gateway / protovalidate 生态对不上。
func protoRendererSource() string {
	return `// renderProtoMessage 用 protojson 渲染响应，保证与 protobuf 生态的 JSON 约定一致。
func renderProtoMessage(w http.ResponseWriter, r *http.Request, v any) error {
	if v == nil {
		w.WriteHeader(http.StatusNoContent)
		return nil
	}
	if rv := reflect.ValueOf(v); rv.Kind() == reflect.Pointer && rv.IsNil() {
		w.WriteHeader(http.StatusNoContent)
		return nil
	}
	m, ok := v.(proto.Message)
	if !ok {
		return muxkit.JSONRenderer{}.Render(w, r, v)
	}
	b, err := protojson.Marshal(m)
	if err != nil {
		return err
	}
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	if c := muxkit.Ctx(r.Context()); c != nil {
		if code := c.Status(); code != 0 {
			w.WriteHeader(code)
		}
	}
	_, err = w.Write(b)
	return err
}
`
}

func buildMethod(g *protogen.GeneratedFile, m *protogen.Method, svc *protogen.Service, im *imports) *methodCode {
	opts, _ := m.Desc.Options().(*descriptorpb.MethodOptions)
	if opts == nil || !proto.HasExtension(opts, annotations.E_Http) {
		return nil
	}
	rule := proto.GetExtension(opts, annotations.E_Http).(*annotations.HttpRule)

	var regs []string
	var binds []string
	rules := append([]*annotations.HttpRule{rule}, rule.GetAdditionalBindings()...)

	for i, br := range rules {
		method, path := patternOf(br)
		if method == "" || path == "" {
			continue
		}
		opID := string(m.GoName)
		suffix := ""
		if i > 0 {
			opID = fmt.Sprintf("%s_%d", m.GoName, i)
			suffix = fmt.Sprintf("_%d", i)
		}
		bindName := fmt.Sprintf("bind%sRequest%s", m.GoName, suffix)

		body, err := buildBindFunc(g, m, path, br.GetBody(), method, bindName, im)
		if err != nil {
			// 生成不了的绑定就退回反射绑定，别让 protoc 整个失败
			regs = append(regs, buildReg(m, svc, method, path, opID, ""))
			continue
		}
		regs = append(regs, buildReg(m, svc, method, path, opID, bindName))
		binds = append(binds, body)
	}
	if len(regs) == 0 {
		return nil
	}

	return &methodCode{
		reg:  strings.Join(regs, "\n"),
		bind: strings.Join(binds, "\n"),
	}
}

// buildReg 生成路由注册语句。绑定不再靠链式声明，而是直接挂生成的函数。
func buildReg(m *protogen.Method, svc *protogen.Service, method, path, opID, bindName string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "r.%s(%q, srv.%s).\n\t\tOperationID(%q).\n\t\tTags(%q).",
		method, path, m.GoName, opID, svc.GoName)
	if c := leadingComment(m); c != "" {
		fmt.Fprintf(&b, "\n\t\tSummary(%q).", c)
	}
	if bindName != "" {
		fmt.Fprintf(&b, "\n\t\tBindFunc(%s).", bindName)
	}
	b.WriteString("\n\t\tRenderer(muxkit.RendererFunc(renderProtoMessage))")
	return b.String()
}

func patternOf(rule *annotations.HttpRule) (method, path string) {
	switch p := rule.GetPattern().(type) {
	case *annotations.HttpRule_Get:
		return "GET", p.Get
	case *annotations.HttpRule_Post:
		return "POST", p.Post
	case *annotations.HttpRule_Put:
		return "PUT", p.Put
	case *annotations.HttpRule_Patch:
		return "PATCH", p.Patch
	case *annotations.HttpRule_Delete:
		return "DELETE", p.Delete
	case *annotations.HttpRule_Custom:
		return strings.ToUpper(p.Custom.GetKind()), p.Custom.GetPath()
	}
	return "", ""
}

// buildBindFunc 生成完整的绑定函数：path → body → query。
// 顺序不能变：body 会把字段置零，必须在 path / query 之后解会被覆盖，所以先解 body。
func buildBindFunc(g *protogen.GeneratedFile, m *protogen.Method, path, bodyField, method, name string, im *imports) (string, error) {
	im.add("net/http")

	inPath := map[string]bool{}
	for _, seg := range pathParamRe.FindAllStringSubmatch(path, -1) {
		n := seg[1]
		if i := strings.Index(n, "="); i >= 0 {
			n = n[:i]
		}
		n = strings.TrimSuffix(n, "...")
		if n != "" {
			inPath[n] = true
		}
	}

	// google.api.http 没写 body 但方法带 body 时，按 REST 惯例整体映射
	effectiveBody := bodyField
	if effectiveBody == "" && (method == "POST" || method == "PUT" || method == "PATCH") {
		effectiveBody = "*"
	}
	hasBody := effectiveBody != ""

	var b strings.Builder
	fmt.Fprintf(&b, "// %s 由 google.api.http 生成：path 取自 URL 模板，body / query 的划分也来自注解。\n", name)
	fmt.Fprintf(&b, "func %s(r *http.Request, dst *%s) error {\n", name, m.Input.GoIdent.GoName)

	// 1. body 先解
	if hasBody {
		im.add("io")
		im.add("google.golang.org/protobuf/encoding/protojson")
		target := "dst"
		if effectiveBody != "*" {
			if f := findField(m.Input, effectiveBody); f != nil && f.Message != nil {
				fmt.Fprintf(&b, "\tif dst.%s == nil {\n\t\tdst.%s = &%s{}\n\t}\n",
					f.GoName, f.GoName, g.QualifiedGoIdent(f.Message.GoIdent))
				target = "dst." + string(f.GoName)
			}
		}
		b.WriteString("\tif r.Body != nil && r.ContentLength != 0 {\n")
		b.WriteString("\t\tdata, err := io.ReadAll(r.Body)\n")
		b.WriteString("\t\tif err != nil {\n\t\t\treturn &muxkit.BindError{Err: err}\n\t\t}\n")
		fmt.Fprintf(&b, "\t\tif err := protojson.Unmarshal(data, %s); err != nil {\n", target)
		b.WriteString("\t\t\treturn &muxkit.BindError{Err: err}\n\t\t}\n")
		b.WriteString("\t}\n")
	}

	// 2. path 覆盖
	for _, n := range sortedPathParams(inPath) {
		f := findField(m.Input, n)
		if f == nil {
			return "", fmt.Errorf("path 参数 %q 在 %s 里找不到对应字段", n, m.Input.GoIdent.GoName)
		}
		assign, err := scalarAssign(g, "dst."+string(f.GoName), f, "v", im)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "\tif v := r.PathValue(%q); v != \"\" {\n\t\t%s\n\t}\n", n, assign)
	}

	// 3. query 覆盖：path 用掉的、body 整体占掉的都不再取
	if effectiveBody != "*" {
		var qfields []*protogen.Field
		for _, f := range m.Input.Fields {
			if inPath[string(f.Desc.Name())] || inPath[string(f.Desc.JSONName())] {
				continue
			}
			if effectiveBody != "" && string(f.Desc.Name()) == effectiveBody {
				continue
			}
			if f.Desc.IsMap() || f.Message != nil {
				continue // 嵌套 message / map 没法从 query 绑
			}
			qfields = append(qfields, f)
		}
		if len(qfields) > 0 {
			b.WriteString("\tq := r.URL.Query()\n")
			for _, f := range qfields {
				if !queryField(g, &b, f, im) {
					continue
				}
			}
		}
	}

	b.WriteString("\treturn nil\n}\n")
	return b.String(), nil
}

// queryField 生成单个字段的 query 绑定。
func queryField(g *protogen.GeneratedFile, b *strings.Builder, f *protogen.Field, im *imports) bool {
	wire := string(f.Desc.JSONName())

	if f.Desc.IsList() {
		elemType := scalarGoType(g, f)
		if elemType == "" {
			return false
		}
		assign, err := scalarAssign(g, "elem", f, "v", im)
		if err != nil {
			return false
		}
		fmt.Fprintf(b, "\tif vs, ok := q[%q]; ok {\n", wire)
		fmt.Fprintf(b, "\t\tdst.%s = make([]%s, 0, len(vs))\n", f.GoName, elemType)
		b.WriteString("\t\tfor _, v := range vs {\n")
		fmt.Fprintf(b, "\t\t\tvar elem %s\n", elemType)
		fmt.Fprintf(b, "\t\t\t%s\n", assign)
		fmt.Fprintf(b, "\t\t\tdst.%s = append(dst.%s, elem)\n", f.GoName, f.GoName)
		b.WriteString("\t\t}\n\t}\n")
		return true
	}

	assign, err := scalarAssign(g, "dst."+string(f.GoName), f, "vs[0]", im)
	if err != nil {
		return false
	}
	fmt.Fprintf(b, "\tif vs, ok := q[%q]; ok && len(vs) > 0 {\n", wire)
	fmt.Fprintf(b, "\t\t%s\n\t}\n", assign)
	return true
}

// scalarAssign 生成把字符串 src 转成目标类型并写入 dst 的代码。
func scalarAssign(g *protogen.GeneratedFile, dst string, f *protogen.Field, src string, im *imports) (string, error) {
	wire := string(f.Desc.JSONName())
	fail := func() string {
		return fmt.Sprintf("return &muxkit.BindError{Field: %q, Err: err}", wire)
	}

	switch f.Desc.Kind() {
	case protoreflect.StringKind:
		return fmt.Sprintf("%s = %s", dst, src), nil

	case protoreflect.BoolKind:
		im.add("strconv")
		return fmt.Sprintf("if b, err := strconv.ParseBool(%s); err != nil {\n\t\t\t%s\n\t\t} else {\n\t\t\t%s = b\n\t\t}", src, fail(), dst), nil

	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		im.add("strconv")
		return fmt.Sprintf("if n, err := strconv.ParseInt(%s, 10, 32); err != nil {\n\t\t\t%s\n\t\t} else {\n\t\t\t%s = int32(n)\n\t\t}", src, fail(), dst), nil

	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		im.add("strconv")
		return fmt.Sprintf("if n, err := strconv.ParseInt(%s, 10, 64); err != nil {\n\t\t\t%s\n\t\t} else {\n\t\t\t%s = n\n\t\t}", src, fail(), dst), nil

	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		im.add("strconv")
		return fmt.Sprintf("if n, err := strconv.ParseUint(%s, 10, 32); err != nil {\n\t\t\t%s\n\t\t} else {\n\t\t\t%s = uint32(n)\n\t\t}", src, fail(), dst), nil

	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		im.add("strconv")
		return fmt.Sprintf("if n, err := strconv.ParseUint(%s, 10, 64); err != nil {\n\t\t\t%s\n\t\t} else {\n\t\t\t%s = n\n\t\t}", src, fail(), dst), nil

	case protoreflect.FloatKind:
		im.add("strconv")
		return fmt.Sprintf("if n, err := strconv.ParseFloat(%s, 32); err != nil {\n\t\t\t%s\n\t\t} else {\n\t\t\t%s = float32(n)\n\t\t}", src, fail(), dst), nil

	case protoreflect.DoubleKind:
		im.add("strconv")
		return fmt.Sprintf("if n, err := strconv.ParseFloat(%s, 64); err != nil {\n\t\t\t%s\n\t\t} else {\n\t\t\t%s = n\n\t\t}", src, fail(), dst), nil

	case protoreflect.BytesKind:
		im.add("encoding/base64")
		return fmt.Sprintf("if raw, err := base64.StdEncoding.DecodeString(%s); err != nil {\n\t\t\t%s\n\t\t} else {\n\t\t\t%s = raw\n\t\t}", src, fail(), dst), nil

	case protoreflect.EnumKind:
		// 数字和 proto 里定义的枚举名都接受
		im.add("strconv")
		enumName := g.QualifiedGoIdent(f.Enum.GoIdent)
		return fmt.Sprintf("if n, err := strconv.ParseInt(%s, 10, 32); err == nil {\n\t\t\t%s = %s(n)\n\t\t} else if ev, ok := %s_value[%s]; ok {\n\t\t\t%s = %s(ev)\n\t\t} else {\n\t\t\t%s\n\t\t}",
			src, dst, enumName, enumName, src, dst, enumName, fail()), nil

	default:
		return "", fmt.Errorf("muxkit: 字段 %s 的类型 %s 不能从 query/path 绑定", f.Desc.Name(), f.Desc.Kind())
	}
}

func scalarGoType(g *protogen.GeneratedFile, f *protogen.Field) string {
	switch f.Desc.Kind() {
	case protoreflect.StringKind:
		return "string"
	case protoreflect.BoolKind:
		return "bool"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "uint32"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "uint64"
	case protoreflect.FloatKind:
		return "float32"
	case protoreflect.DoubleKind:
		return "float64"
	case protoreflect.BytesKind:
		return "[]byte"
	case protoreflect.EnumKind:
		return g.QualifiedGoIdent(f.Enum.GoIdent)
	}
	return ""
}

func findField(md *protogen.Message, name string) *protogen.Field {
	for _, f := range md.Fields {
		if string(f.Desc.Name()) == name || string(f.Desc.JSONName()) == name {
			return f
		}
	}
	return nil
}

func leadingComment(m *protogen.Method) string {
	if m.Comments.Leading.String() == "" {
		return ""
	}
	lines := strings.Split(strings.TrimSpace(m.Comments.Leading.String()), "\n")
	var kept []string
	for _, l := range lines {
		l = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(l), "//"))
		if l != "" {
			kept = append(kept, l)
		}
	}
	return strings.Join(kept, " ")
}

func sortedPathParams(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func quoted(s string) string { return `"` + s + `"` }
